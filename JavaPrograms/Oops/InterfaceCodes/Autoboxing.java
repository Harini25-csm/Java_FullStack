package Oops.InterfaceCodes;

public class Autoboxing {
    public static void main(String[] args) {
        int i=1;
        Integer i1=i;
        System.out.println(i1);
        long l=32984744862353l;
        Long l1=l;
        System.out.println(l1);
        double d=55.43;
        Double d1=d;
        System.out.println(d1);
    }
        
}
